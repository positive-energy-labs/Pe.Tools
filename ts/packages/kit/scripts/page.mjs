import { readFile, writeFile } from "node:fs/promises";

const page = new URL("../../../../examples/pods/snowdon-circuits/pages/tour/", import.meta.url);
const read = async (name) => (await readFile(new URL(name, page), "utf8")).replaceAll("\r\n", "\n");
const route = new URL(
  "../../../../examples/pods/snowdon-circuits/routes/voltage-drop/",
  import.meta.url,
);
const [template, calc, circuits, styles, instruments, app, routeSource] = await Promise.all([
  read("index.source.html"),
  read("calc.mjs"),
  read("circuits.mjs"),
  read("styles.mjs"),
  read("instruments.mjs"),
  read("page.js"),
  readFile(new URL("index.source.mjs", route), "utf8").then((text) =>
    text.replaceAll("\r\n", "\n"),
  ),
]);
// This authored graph contains only local, single-line imports. React and kit belong to each shell.
const body = (source) => source.replace(/^import[^\n]*\n/gm, "").replace(/^export /gm, "");
const shared = [calc, circuits, styles, instruments].map(body).join("\n");
const sources = { calc, circuits, styles, instruments, app };
const safeScript = (text) => text.replace(/<\/script/gi, "<\\/script");
const html = template
  .replace("<!-- KIT -->", () => '<script src="/pages/pe.js"></script>')
  .replace(
    "<!-- SOURCE -->",
    () =>
      `<script id="page-source" type="application/json">${safeScript(JSON.stringify(sources))}</script>`,
  )
  .replace("<!-- PAGE -->", () => `<script>${safeScript(shared)}\n${safeScript(app)}</script>`);
await writeFile(new URL("index.html", page), html);
const routeBody = routeSource
  .replace(/^import[^\n]*\n/gm, "")
  .replace("/* AUTHORED SOURCES */ {}", () =>
    JSON.stringify({ calc, circuits, styles, instruments, route: routeSource }),
  );
const esm = `// Generated by @pe/kit scripts/page.mjs from the authored Snowdon Circuits modules.\n${shared}\n${routeBody.trimEnd()}\n`;
await writeFile(new URL("index.js", route), esm);
console.log(`Hosted Page: ${Buffer.byteLength(html)} bytes; portable export is owned by the host`);
console.log(
  `Authored route: ${Buffer.byteLength(esm)} bytes; React and kit are supplied by the app`,
);
