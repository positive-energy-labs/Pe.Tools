/**
 * The C# half of the route contract. Revit commands open web routes (`PeToolsBrowser`), and the
 * path and URL keys they write must be the contract's, not a second copy typed by hand. This
 * projects every route's path and shareable URL keys (a draft key is never in a link) into
 * `dotnet/Pe.App/Host/PeRoutes.generated.cs`.
 *
 *   (none)   write the file
 *   --check  exit 1 when the file differs from the contract (a test runs the same render)
 *
 * Why a generated table and not a host call: the producers run in the Revit process, often before
 * the host is up, and a launch needs only a path and key names. The values still come from the
 * contract's own `link` semantics on the TS side; C# just joins names and escaped values.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { routeAddresses } from "../src/routes/index.ts";
import { threadListFields } from "../src/routes/shared.ts";

const HERE = dirname(fileURLToPath(import.meta.url));
export const ROUTES_CS = resolve(HERE, "../../../../dotnet/Pe.App/Host/PeRoutes.generated.cs");

const pascal = (text: string) =>
  text
    .split(/[-_]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

/** The generated C#, deterministic: routes and keys in declaration order, LF endings. */
export function renderRoutesCs(): string {
  const routes = Object.entries(routeAddresses).map(([route, spec]) => {
    const keys = Object.entries({ ...threadListFields, ...spec.fields } as Record<
      string,
      { url?: string; share?: false }
    >)
      .filter(([, field]) => field.url && field.share !== false)
      .map(([key]) => `            public const string ${pascal(key)} = "${key}";`);
    return [
      `    /// <summary>${spec.title}: <c>${spec.path}</c>.</summary>`,
      `    internal static class ${pascal(route)} {`,
      `        public const string Path = "${spec.path}";`,
      `        /// <summary>The URL keys a link may carry.</summary>`,
      `        internal static class Keys {`,
      ...keys,
      `        }`,
      `    }`,
    ].join("\n");
  });
  return [
    "// <auto-generated>",
    "// From ts/packages/agent-contracts/src/routes/*.ts by `pnpm codegen:routes` in that package.",
    "// Edit a route's address there, then regenerate; never edit this file.",
    "// </auto-generated>",
    "namespace Pe.App.Host;",
    "",
    "/// <summary>Every web route's path and shareable URL keys, from the route contract.</summary>",
    "internal static class PeRoutes {",
    routes.join("\n\n"),
    "}",
    "",
  ].join("\n");
}

if (import.meta.main) {
  const text = renderRoutesCs();
  if (process.argv.includes("--check")) {
    const found = existsSync(ROUTES_CS)
      ? readFileSync(ROUTES_CS, "utf8").replaceAll("\r\n", "\n")
      : "";
    if (found !== text) {
      console.error(
        "PeRoutes.generated.cs is stale. Run `pnpm codegen:routes` in ts/packages/agent-contracts.",
      );
      process.exit(1);
    }
  } else writeFileSync(ROUTES_CS, text);
}
