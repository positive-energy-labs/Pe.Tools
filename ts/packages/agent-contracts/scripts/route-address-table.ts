/**
 * Renders the address table, `src/routes/table.generated.ts` (ADR 0035 rule 4, slice 5a): every
 * route's address by route key, one file. `codegen:routes` (`apps/web/scripts/route-graphs.ts`)
 * hands it one row per route key. A row with `body` is projected from a web declaration; a row
 * without is hand-written in the file `HAND_ADDRESSES` names. `module` is the web folder of the
 * builtin declaration whose key is the row's key: the builtin set is derived from it.
 */
export interface AddressRow {
  readonly key: string;
  readonly module?: string;
  /** The address object literal, `{ path, title, fields, agent? }`; absent for a hand row. */
  readonly body?: string;
}

/** Addresses no declaration projects: its fields carry codecs a JSON schema cannot. */
export const HAND_ADDRESSES: Readonly<Record<string, readonly [name: string, file: string]>> = {
  pea: ["peaAddress", "./pea.ts"],
  "session-admin": ["sessionAdminAddress", "./g4-splits.ts"],
  space: ["spaceAddress", "./space.ts"],
};

export function renderAddressTable(rows: readonly AddressRow[]): string {
  const sorted = [...rows].sort((a, b) => a.key.localeCompare(b.key));
  const keys = new Set(sorted.map((row) => row.key));
  if (keys.size !== sorted.length) throw Error("Duplicate address row");
  for (const key of Object.keys(HAND_ADDRESSES))
    if (!keys.has(key)) throw Error(`The hand address ${key} has no row`);
  const bodies = sorted.flatMap((row) => (row.body ? [row.body] : []));
  const uses = (text: string) => bodies.some((body) => body.includes(text));
  const imports = [
    `import { z } from "zod";`,
    ...(uses("Immutable<") ? [`import type { Immutable } from "../route-kernel-data.ts";`] : []),
    `import { ${uses("subjectSchema(") ? "subjectSchema, " : ""}focusSelectionSchema } from "../route-kernel-codecs.ts";`,
    `import { jsonCodec, type RouteDeclaration } from "../route-field.ts";`,
    ...sorted.flatMap((row) => {
      const hand = !row.body && HAND_ADDRESSES[row.key];
      if (!row.body && !hand) throw Error(`${row.key}: no declaration projects it and no hand file holds it`);
      return hand ? [`import { ${hand[0]} } from "${hand[1]}";`] : [];
    }),
  ];
  const helpers = [
    `const field = <S extends z.ZodType>(schema: S, url: "push" | "replace") => ({ schema, url, agent: "set" as const, codec: jsonCodec(schema) });`,
    ...(uses("personField(")
      ? [`const personField = <S extends z.ZodType>(schema: S, url: "push" | "replace") => ({ schema, url, codec: jsonCodec(schema) });`]
      : []),
  ];
  const entries = sorted.map((row) => {
    const module = row.module ? `, module: ${JSON.stringify(row.module)}` : "";
    const value = row.body
      ? `${row.body.slice(0, -1).trimEnd()}${module} }`
      : module ? `{ ...${HAND_ADDRESSES[row.key]![0]}${module} }` : HAND_ADDRESSES[row.key]![0];
    return `${JSON.stringify(row.key)}: ${value}`;
  });
  return [
    "// Generated by codegen:routes: the address table. Do not edit.",
    ...imports,
    ...helpers,
    "/** Every route's address, by route key. A row with `module` is a builtin declared in that web folder. */",
    `export const routeAddresses = {\n${entries.join(",\n")},\n} satisfies Record<string, RouteDeclaration>;`,
    "",
  ].join("\n");
}
