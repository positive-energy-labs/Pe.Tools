/**
 * Renders the one generated route registry, `apps/host/src/routes.generated.ts` (ADR 0035 rule 4,
 * slice 5a). `codegen:routes` (`route-graphs.ts`) hands it one row per builtin declaration; the
 * emitted file carries one static import per host read module, per closure and per Work, so
 * rolldown pack and jiti dev both link it. Paths in a row are relative to `apps/web/src/`.
 */
import { posix } from "node:path";

export interface RouteRegistryInput {
  readonly key: string;
  readonly schemas?: Readonly<Record<string, unknown>>;
  /** The route directory relative to `apps/web/src/`; a product's climbs out to `ts/products/<product>/web`. */
  readonly folder: string;
  /** The host read module `route.ts` names, relative to the declaration (`./host.ts`); absent when the route has none. */
  readonly host?: string;
  /**
   * The Work, as `projectWork(..., exported = false)` returns it for this file: `definition` binds
   * `name` from wherever `route.ts` imports it (the route directory, or contracts), and
   * `properties` read `data` and `work`. Contracts never hold a projection of an app's Work.
   */
  readonly work?: {
    readonly name: string;
    readonly definition: string;
    readonly properties: string;
  };
}

const HEADER = "// Generated by codegen:routes: the one route registry. Do not edit.";

export function renderRouteRegistry(rows: readonly RouteRegistryInput[]): string {
  const keys = new Set<string>();
  const imports = [
    `import type { RouteRegistry } from "./route-registry.ts";`,
    `import { closureSchema } from "../../web/src/route/builtin-closure.ts";`,
    `import { z } from "zod";`,
  ];
  const works: string[] = [];
  const entries = rows.map((row, index) => {
    if (keys.has(row.key)) throw Error(`Duplicate route key ${row.key}`);
    keys.add(row.key);
    const web = posix.join("../../web/src", row.folder);
    imports.push(
      `import c${index} from "${web}/source-closure.generated.json" with { type: "json" };`,
    );
    if (row.host) {
      if (!row.host.startsWith("./") && !row.host.startsWith("@pe/"))
        throw Error(`${row.key}: declare a route-relative host module or an exported host package`);
      const host = row.host.startsWith("./") ? `${web}/${row.host.slice(2)}` : row.host;
      imports.push(`import * as h${index} from "${host}";`);
    }
    if (row.work) {
      const lines = row.work.definition.trimEnd().split("\n");
      imports.push(...lines.filter((line) => line.startsWith("import ")));
      works.push(...lines.filter((line) => !line.startsWith("import ")));
    }
    // The projected properties name `data` and `work`; default parameters bind them per row.
    const projectedSchemas = Object.entries(row.schemas ?? {})
      .map(([id, schema]) => `${JSON.stringify(id)}: z.fromJSONSchema(${JSON.stringify(schema)}).meta(${JSON.stringify(schema)})`)
      .join(",");
    const module = [
      row.work
        ? `...((data = r${index}.envelope.data, work = ${row.work.name}) => ({ data, ${row.work.properties.replace("schemas:{", `schemas:{${projectedSchemas},`)} }))()`
        : `data: r${index}.envelope.data, schemas: {${projectedSchemas}}`,
      ...(row.host ? [`reads: h${index}.reads`] : []),
    ].join(", ");
    return `${JSON.stringify(row.key)}: { key: ${JSON.stringify(row.key)}, closure: r${index}, host: { ${module} } }`;
  });
  const parsed = rows.map((_row, index) => `const r${index} = closureSchema.parse(c${index});`);
  return [
    HEADER,
    ...imports,
    ...works,
    ...parsed,
    `export const routeRegistry: RouteRegistry = {\n${entries.join(",\n")},\n};`,
    "",
  ].join("\n");
}
