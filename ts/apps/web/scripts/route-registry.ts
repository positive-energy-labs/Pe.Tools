/**
 * Renders the one generated route registry, `apps/host/src/routes.generated.ts` (ADR 0035 rule 4,
 * slice 5a). `codegen:routes` (`route-graphs.ts`) hands it one row per builtin declaration; the
 * emitted file carries one static import per host read module and per closure, so rolldown pack
 * and jiti dev both link it. Paths in a row are relative to `apps/web/src/`.
 */
export interface RouteRegistryInput {
  readonly key: string;
  readonly folder: string;
  readonly address: string;
  readonly contract: string;
  readonly dock: boolean;
  /** The host read module `route.ts` names, relative to the declaration (`./host.ts`); absent when the route has none. */
  readonly host?: string;
  /** The work projection, as `projectWork` returns it: the import line's export name and the module properties. */
  readonly work?: { readonly stateExport: string; readonly file: string; readonly properties: string };
}

const HEADER = "// Generated by codegen:routes: the one route registry. Do not edit.";

export function renderRouteRegistry(rows: readonly RouteRegistryInput[]): string {
  const keys = new Set<string>();
  const imports = [
    `import type { RouteRegistry } from "./route-registry.ts";`,
    `import { closureSchema } from "../../web/src/route/builtin-closure.ts";`,
    ...(rows.some((row) => row.work) ? [`import { z } from "zod";`] : []),
  ];
  const entries = rows.map((row, index) => {
    if (keys.has(row.key)) throw Error(`Duplicate route key ${row.key}`);
    keys.add(row.key);
    const web = `../../web/src/${row.folder}`;
    imports.push(`import c${index} from "${web}/source-closure.generated.json" with { type: "json" };`);
    if (row.host) {
      if (!row.host.startsWith("./")) throw Error(`${row.key}: a host read lives in its route directory, not ${row.host}`);
      imports.push(`import * as h${index} from "${web}/${row.host.slice(2)}";`);
    }
    if (row.work) imports.push(`import { ${row.work.stateExport} as w${index} } from "${row.work.file}";`);
    // The projected properties name `data` and `work`; default parameters bind them per row.
    const module = [
      row.work
        ? `...((data = r${index}.envelope.data, work = w${index}) => ({ data, ${row.work.properties} }))()`
        : `data: r${index}.envelope.data, schemas: {}`,
      ...(row.host ? [`reads: h${index}.reads`] : []),
    ].join(", ");
    return `${JSON.stringify(row.key)}: { key: ${JSON.stringify(row.key)}, folder: ${JSON.stringify(row.folder)}, address: ${JSON.stringify(row.address)}, contract: ${JSON.stringify(row.contract)}, dock: ${row.dock}, closure: r${index}, host: { ${module} } }`;
  });
  const parsed = rows.map((_row, index) => `const r${index} = closureSchema.parse(c${index});`);
  return `${HEADER}\n${imports.join("\n")}\n${parsed.join("\n")}\nexport const routeRegistry: RouteRegistry = {\n${entries.join(",\n")},\n};\n`;
}
