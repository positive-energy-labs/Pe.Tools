import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

/** Package metadata is the product composition authority; the registry owns duplicate and seal checks. */
export function renderProductExecutors(checkout: string): string {
  const products = join(checkout, "ts/products");
  const groups = readdirSync(products).sort().flatMap(product => {
    const file = join(products, product, "host/package.json");
    const pkg = JSON.parse(readFileSync(file, "utf8"));
    const declaration = pkg.pe?.executors;
    if (!declaration) return [];
    if (declaration.sheet && !["losses", "parameters"].includes(declaration.sheet.via))
      throw Error(`Invalid sheet executor via in ${file}: ${declaration.sheet.via}`);
    if (!pkg.exports[declaration.module] || !declaration.arguments.every((a: string) => a === "bridge" || a === "deps"))
      throw Error(`Invalid executor export in ${file}`);
    return [{ name: pkg.name, ...declaration }];
  });
  return [
    "// Generated by codegen:routes from product host package metadata. Do not edit.",
    'import type { RevitBridge } from "@pe/host-internal/bridge";',
    'import type { DocumentRef, NativeProcess } from "@pe/agent-contracts";',
    'import type { HostNativeRead } from "@pe/host-internal/native-read";',
    'import type { FamilyActionDependencies } from "./family-actions.ts";',
    'import type { CommandExecutor } from "@pe/host-internal/command-executor";',
    ...groups.map((g, i) => `import { ${g.factory} as group${i} } from ${JSON.stringify(g.name + g.module.slice(1))};`),
    'export function productExecutors(bridge: RevitBridge["Service"], deps: FamilyActionDependencies & { nativeRead?: HostNativeRead["Service"]; projectLifetime?: (target: DocumentRef) => Promise<NativeProcess> } = {}) {',
    "  const result: Record<string, CommandExecutor> = {};",
    ...groups.map((g, i) => `  for (const [key, executor] of Object.entries(group${i}(${g.arguments.join(", ")}))) { if (result[key]) throw Error(\`Duplicate product executor \${key}\`); result[key] = executor; }`),
    `  return { executors: result, sheetRoutes: ${JSON.stringify(Object.fromEntries(groups.flatMap(g => (g.sheet?.routes ?? []).map((route: string) => [route, g.sheet.via]))))} as Readonly<Record<string, string>> };`,
    "}", "",
  ].join("\n");
}
