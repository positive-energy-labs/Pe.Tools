import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { isDeepStrictEqual } from "node:util";
import { z } from "zod";
import nativeHomes from "../../../packages/host-contracts/src/generated/native-homes.generated.json" with { type: "json" };

export const productAssemblyPaths = {
  actions: "ts/packages/mcps/src/pea/product-actions.generated.ts",
  catalog: "ts/packages/mcps/src/pea/product-catalog.generated.ts",
  contracts: "ts/packages/mcps/src/pea/product-contracts.generated.ts",
  guides: "ts/packages/mcps/src/pea/guides.generated.ts",
  executors: "ts/apps/host/src/product-executors.generated.ts",
  nativeHomes: "ts/packages/agent-contracts/src/generated/native-homes.generated.ts",
  tutorial: "ts/apps/web/src/route/tutorial-products.generated.ts",
};

const manifest = z.object({
  name: z.string(),
  exports: z.record(z.string(), z.unknown()).optional(),
});
const source = (...lines: string[]) =>
  ["// Generated by codegen:routes from product declarations. Do not edit.", ...lines, ""].join(
    "\n",
  );

/** Shared by the route producer and its freshness guard. */
export function renderProductAssembly(checkout: string) {
  const root = join(checkout, "ts/products");
  const folders = readdirSync(root, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
  const read = (id: string, layer: string) => {
    const file = join(root, id, layer, "package.json");
    return existsSync(file) ? manifest.parse(JSON.parse(readFileSync(file, "utf8"))) : undefined;
  };
  const rows = folders.map((id) => ({
    id,
    contract: read(id, "contract"),
    host: read(id, "host"),
    web: read(id, "web"),
    // One route is `web/route.ts`; a product of several keeps each under `web/routes/<name>/`.
    route: ["web/route.ts", "web/routes"].some((path) => existsSync(join(root, id, path))),
  }));
  const declared = rows.flatMap(({ id, contract, host }) => {
    const has = (pkg: typeof contract) => Object.hasOwn(pkg?.exports ?? {}, "./product");
    if (has(contract) !== has(host))
      throw Error(`Product ${id}: the contract and the host must both export ./product`);
    return has(contract) && contract && host ? [{ contract: contract.name, host: host.name }] : [];
  });
  const imports = (layer: "contract" | "host", name: string) =>
    declared.map(
      (row, index) => `import { ${name} as ${name}${index} } from "${row[layer]}/product";`,
    );
  const products = declared.map((_, index) => `product${index}`);
  const members = (key: string) => products.map((product) => `${product}.${key}`);
  const spread = (names: string[]) => names.map((name) => `...${name}`).join(", ");
  const commands = ["builtinCommands", ...members("actions")];
  const tools = ["builtinTools", ...members("tools")];
  const contractImports = imports("contract", "product");
  const hosts = declared.map((_, index) => `host${index}`);
  const names = (values: (string | undefined)[]) =>
    [...new Set(values.filter((name) => name !== undefined))].sort();
  return {
    outputs: {
      [productAssemblyPaths.nativeHomes]: [
        "// Generated by codegen:routes from the native operation catalog. Do not edit.",
        ...Object.entries({
          ownerBlobs: nativeHomes["owner-blob"],
          entities: nativeHomes.entity,
          machineFiles: nativeHomes["machine-file"],
        }).map(
          ([name, rows]) => `export const ${name} = ${JSON.stringify(rows, null, 2)} as const;`,
        ),
        "",
      ].join("\n"),
      [productAssemblyPaths.tutorial]: source(
        'import type { ProductDeclaration } from "@pe/agent-contracts/product";',
        ...contractImports,
        `const products = [${products.join(", ")}] as const;`,
        'export const tutorialProducts: readonly ProductDeclaration[] = products.flatMap<ProductDeclaration>(product => "homes" in product ? [product] : []);',
      ),
      [productAssemblyPaths.actions]: source(
        'import { builtinCommands, builtinTools, targetForCommand, withHostActions } from "@pe/agent-contracts/semantic-actions";',
        'import { assertProductCatalogKeys } from "@pe/agent-contracts/pe-api";',
        'import type { DocumentRef, Tool } from "@pe/agent-contracts";',
        'import { assertUniqueProductKeys } from "./assembly-checks.ts";',
        ...contractImports,
        ...declared.map(
          ({ contract }, i) =>
            `if ("callPolicies" in product${i}) assertProductCatalogKeys("${contract}", "call policy", product${i}.callPolicies as Readonly<Record<string, unknown>>);`,
        ),
        `assertUniqueProductKeys("tool", [${tools.join(", ")}]);`,
        `assertUniqueProductKeys("command", [${commands.join(", ")}]);`,
        `export const tools: ${tools.map((table) => "typeof " + table).join(" & ")} = { ${spread(tools)} };`,
        `export const commands = { ${spread(commands)} };`,
        "export const hostActions = withHostActions(commands);",
        "export type SemanticActionKey = keyof typeof commands;",
        "export type HostActionKey = keyof typeof hostActions;",
        "export const commandTarget = (key: string, input: Record<string, unknown>, document?: DocumentRef) =>",
        "  targetForCommand(hostActions, key, input, document);",
        "export function commandTool(key: string): Tool | undefined {",
        "  return Object.values(tools).find(tool => Object.hasOwn(tool.commands, key));",
        "}",
      ),
      [productAssemblyPaths.catalog]: source(
        'import { createPeCatalog } from "@pe/agent-contracts/pe-api";',
        'import { assertUniqueProductKeys } from "./assembly-checks.ts";',
        'import { hostActions } from "./product-actions.generated.ts";',
        ...contractImports,
        ...["callPolicies", "reads"].map(
          (key) =>
            `const ${key} = [${products.join(", ")}].flatMap(product => "${key}" in product ? [product.${key}] : []);`,
        ),
        'assertUniqueProductKeys("call policy", callPolicies);',
        'assertUniqueProductKeys("named read", reads.map(read => read.inputs));',
        "const catalog = createPeCatalog(hostActions, {",
        "  inputs: Object.assign({}, ...reads.map(read => read.inputs)),",
        '  help: reads.map(read => read.help).filter(Boolean).join(" "),',
        "}, Object.assign({}, ...callPolicies));",
        ...[
          "peRoutes",
          "linkedCatalog",
          "matchPeRoute",
          "servePeRoute",
          "peClientScript",
          "isPeRouteId",
          "createPeClient",
        ].map(
          (name) =>
            `export const ${name}: ReturnType<typeof createPeCatalog>["${name}"] = catalog.${name};`,
        ),
      ),
      [productAssemblyPaths.contracts]: source(
        'import { NATIVE_BODY_VERSION_HEADER, readingRequestSchema } from "@pe/agent-contracts";',
        'import type { SettingOwner } from "@pe/agent-contracts/setting-owners";',
        'import { z } from "zod";',
        'import { assertUniqueProductKeys } from "./assembly-checks.ts";',
        ...contractImports,
        `const products = [${products.join(", ")}] as const;`,
        'export const resourceReadingSchema = z.union([readingRequestSchema, ...products.flatMap(product => "resourceInputs" in product ? [...product.resourceInputs] : [])]);',
        'const owners = products.flatMap(product => "settingOwners" in product ? [product.settingOwners] : []);',
        'assertUniqueProductKeys("settings owner", owners);',
        "export const settingOwners: Readonly<Record<string, SettingOwner>> = Object.freeze(Object.assign({}, ...owners));",
        'const headersByProduct = products.flatMap(product => "basisHeaders" in product ? [product.basisHeaders] : []);',
        'assertUniqueProductKeys("basis header", headersByProduct);',
        "export const readingBasisHeaders = (headers: Readonly<Record<string, string | undefined>>) => ({",
        "  ...Object.fromEntries(headersByProduct.flatMap(names => Object.entries(names).map(([name, header]) => [name, headers[header]]))),",
        "  version: headers[NATIVE_BODY_VERSION_HEADER],",
        "});",
      ),
      [productAssemblyPaths.guides]: source(
        ...contractImports,
        `const products = [${products.join(", ")}] as const;`,
        'export const productGuides = products.flatMap(product => "guide" in product ? [product.guide] : []);',
        'export const productAdmissionPreflights = products.flatMap(product => "admissionPreflight" in product ? [product.admissionPreflight] : []);',
      ),
      [productAssemblyPaths.executors]: source(
        ...imports("host", "host"),
        'import { bindProducts } from "./product-runtime.ts";',
        `export const { productExecutors, productReads } = bindProducts([${hosts.join(", ")}]);`,
      ),
    },
    dependencies: {
      "ts/packages/mcps/package.json": names(declared.map((row) => row.contract)),
      "ts/apps/host/package.json": names([
        ...declared.map((row) => row.host),
        ...rows.filter((row) => row.route).flatMap((row) => [row.host?.name, row.contract?.name]),
      ]),
      "ts/apps/web/package.json": names([
        ...declared.map((row) => row.contract),
        ...rows.filter((row) => row.route).map((row) => row.web?.name),
      ]),
    },
  };
}

const dependenciesSchema = z
  .object({
    dependencies: z.record(z.string(), z.string()).optional(),
    devDependencies: z.record(z.string(), z.string()).optional(),
    pe: z
      .object({ generatedProductDependencies: z.array(z.string()).optional() })
      .loose()
      .optional(),
  })
  .loose();

/** Workspace links are still pnpm dependencies. Keep hand-authored dependencies and replace the generated rows. */
export function productDependencyChanges(
  checkout: string,
  expected: Readonly<Record<string, readonly string[]>>,
) {
  return Object.entries(expected).flatMap(([file, packages]) => {
    const json = z
      .record(z.string(), z.unknown())
      .parse(JSON.parse(readFileSync(join(checkout, file), "utf8")));
    const current = dependenciesSchema.parse(json);
    const dependencies = { ...current.dependencies };
    const devDependencies = { ...current.devDependencies };
    for (const name of current.pe?.generatedProductDependencies ?? []) delete dependencies[name];
    for (const name of packages) {
      const version = dependencies[name] ?? devDependencies[name];
      if (version && version !== "workspace:*")
        throw Error(file + ": expected a workspace dependency on " + name);
      dependencies[name] = "workspace:*";
      delete devDependencies[name];
    }
    const next = {
      ...json,
      dependencies,
      ...(current.devDependencies && { devDependencies }),
      pe: { ...current.pe, generatedProductDependencies: packages },
    };
    return isDeepStrictEqual(json, next)
      ? []
      : [{ file, text: JSON.stringify(next, null, 2) + "\n" }];
  });
}
