import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

/** Contract metadata registers guides and preflights without product names in generic acquisition. */
export function renderProductGuides(checkout: string): string {
  const products = join(checkout, "ts/products");
  const packages = readdirSync(products).sort().map((product) => {
    const file = join(products, product, "contract/package.json");
    return { file, pkg: JSON.parse(readFileSync(file, "utf8")) };
  });
  const modules = (field: string) => packages.flatMap(({ file, pkg }) => {
    const module = pkg.pe?.[field];
    if (!module) return [];
    if (!pkg.exports[module]) throw Error(`Invalid ${field} export in ${file}`);
    return [pkg.name + module.slice(1)];
  });
  const guides = modules("guide");
  const preflights = modules("admissionPreflight");
  return [
    "// Generated by codegen:routes from product contract metadata. Do not edit.",
    ...guides.map((module, i) => `import { peaGuide as guide${i} } from ${JSON.stringify(module)};`),
    `export const productGuides = [${guides.map((_, i) => `guide${i}`).join(", ")}] as const;`,
    ...preflights.map((module, i) => `import { admissionPreflight as preflight${i} } from ${JSON.stringify(module)};`),
    `export const productAdmissionPreflights = [${preflights.map((_, i) => `preflight${i}`).join(", ")}] as const;`,
    "",
  ].join("\n");
}
