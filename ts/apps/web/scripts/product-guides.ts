import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

/** Contract package metadata registers product text without teaching generic acquisition product names. */
export function renderProductGuides(checkout: string): string {
  const products = join(checkout, "ts/products");
  const guides = readdirSync(products).sort().flatMap((product) => {
    const file = join(products, product, "contract/package.json");
    const pkg = JSON.parse(readFileSync(file, "utf8"));
    const module = pkg.pe?.guide;
    if (!module) return [];
    if (!pkg.exports[module]) throw Error(`Invalid guide export in ${file}`);
    return [`../../../../products/${product}/contract/${pkg.exports[module].slice(2)}`];
  });
  return [
    "// Generated by codegen:routes from product contract metadata. Do not edit.",
    ...guides.map((module, i) => `import { peaGuide as guide${i} } from ${JSON.stringify(module)};`),
    `export const productGuides = [${guides.map((_, i) => `guide${i}`).join(", ")}] as const;`,
    "",
  ].join("\n");
}
